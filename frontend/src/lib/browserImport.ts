// The userscript's private storage pairs a deliberate menu action with one intake tab.
export function browserImportScript(origin: string) {
  const app = new URL(origin)
  return [
    '// ==UserScript==',
    '// @name JAV Pilot 浏览器入库',
    '// @namespace jav-pilot',
    '// @version 1.1',
    ...['javdb.com', 'www.javbus.com', 'missav.ws', 'missav.ai', 'jable.tv', '123av.com'].map(
      (host) => '// @match https://' + host + '/*',
    ),
    '// @match ' + app.protocol + '//' + app.hostname + '/*',
    '// @grant GM_registerMenuCommand',
    '// @grant GM_setValue',
    '// @grant GM_getValue',
    '// @grant GM_deleteValue',
    '// @run-at document-idle',
    '// ==/UserScript==',
    '(() => {',
    '  const app = ' + JSON.stringify(app.origin) + ';',
    '  if (location.origin === app) {',
    "    if (location.pathname !== '/explore') return;",
    '    const token = location.hash.slice(1);',
    '    if (!/^[a-f0-9-]{36}$/.test(token)) return;',
    '    const request = GM_getValue(token);',
    '    GM_deleteValue(token);',
    "    if (!request || Date.now() > request.expires || new URLSearchParams(location.search).get('code') !== request.code) return;",
    '    const observer = new MutationObserver(submit);',
    '    function submit() {',
    "      const form = document.querySelector('[data-browser-import-code]');",
    '      if (form?.dataset.browserImportCode !== request.code) return;',
    "      const button = form.querySelector('button:not([disabled])');",
    '      if (!button) return;',
    '      observer.disconnect(); button.click();',
    '    }',
    '    observer.observe(document.body, {subtree:true, childList:true});',
    '    setTimeout(() => observer.disconnect(), 30000); submit(); return;',
    '  }',
    "  GM_registerMenuCommand('加入 JAV Pilot', () => {",
    '    const selected = window.getSelection()?.toString().trim();',
    "    const found = (selected || document.querySelector('h1')?.textContent || document.title).match(/(?:FC2[- ]?(?:PPV[- ]?)?\\d{3,9}|[a-z]{2,12}[-_]\\d{2,8})/i);",
    "    if (!found) { alert('请先选中作品番号'); return; }",
    "    const token = crypto.randomUUID(), url = new URL('/explore', app);",
    '    GM_setValue(token, {code:found[0],expires:Date.now()+120000});',
    "    url.searchParams.set('code',found[0]); url.hash=token;",
    "    window.open(url,'_blank','noopener');",
    '  });',
    '})();',
  ].join('\n')
}
